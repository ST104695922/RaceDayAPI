CREATE DATABASE RACEDAY;

USE RACEDAY;


CREATE TABLE USERS(
    USER_ID CHAR(5) PRIMARY KEY,
    FULL_NAME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(100) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR(255) NOT NULL,
    ROLE VARCHAR(20) NOT NULL DEFAULT 'Participant'
);

-- 2. ORGANISER table 
CREATE TABLE ORGANISER(
    ORGANISER_ID CHAR(5) PRIMARY KEY,
    FULL_NAME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(100) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR(255) NOT NULL
);

-- 3. EVENT table
CREATE TABLE EVENT(
    EVENT_ID CHAR(5) PRIMARY KEY,
    EVENT_NAME VARCHAR(100) NOT NULL,
    EVENT_DATE DATE NOT NULL,
    LOCATION VARCHAR(100) NOT NULL,
    STATUS VARCHAR(20) NOT NULL DEFAULT 'Upcoming',
    ORGANISER_ID CHAR(5) NOT NULL,
    FOREIGN KEY (ORGANISER_ID) REFERENCES ORGANISER(ORGANISER_ID)
);

-- 4. CATEGORY table 
CREATE TABLE CATEGORY(
    CATEGORY_ID CHAR(5) PRIMARY KEY,
    EVENT_ID CHAR(5) NOT NULL,
    CATEGORY_NAME VARCHAR(50) NOT NULL,
    DISTANCE_KM DECIMAL(5,2) NOT NULL,
    ENTRY_FEE DECIMAL(8,2) NOT NULL DEFAULT 0,
    FOREIGN KEY (EVENT_ID) REFERENCES EVENT(EVENT_ID)
);

-- 5. ENROLMENT table 
CREATE TABLE ENROLMENT(
    ENROLMENT_ID CHAR(5) PRIMARY KEY,
    PARTICIPANT_ID CHAR(5) NOT NULL,
    CATEGORY_ID CHAR(5) NOT NULL,
    ENROLMENT_DATE DATE NOT NULL DEFAULT GETDATE(),
    STATUS VARCHAR(20) NOT NULL DEFAULT 'Pending',
    FOREIGN KEY (PARTICIPANT_ID) REFERENCES USERS(USER_ID),
    FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORY(CATEGORY_ID)
);

-- 6. PAYMENT table
CREATE TABLE PAYMENT(
    PAYMENT_ID CHAR(5) PRIMARY KEY,
    ENROLMENT_ID CHAR(5) NOT NULL,
    AMOUNT DECIMAL(8,2) NOT NULL,
    PAYMENT_DATE DATE NOT NULL DEFAULT GETDATE(),
    PAYMENT_STATUS VARCHAR(20) NOT NULL DEFAULT 'Pending',
    TRANSACTION_REF VARCHAR(50),
    FOREIGN KEY (ENROLMENT_ID) REFERENCES ENROLMENT(ENROLMENT_ID)
);

-- 7. RESULT table
CREATE TABLE RESULT(
    RESULT_ID CHAR(5) PRIMARY KEY,
    ENROLMENT_ID CHAR(5) NOT NULL UNIQUE,
    FINISH_TIME TIME NOT NULL,
    POSITION INT,
    FOREIGN KEY (ENROLMENT_ID) REFERENCES ENROLMENT(ENROLMENT_ID)
);

